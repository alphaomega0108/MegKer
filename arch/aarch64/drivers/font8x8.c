/* arch/x86_64/drivers/font8x8.c
 * Minimal 8x8 bitmap font: space, '!', ',', '-', '.', ':', digits,
 * and uppercase A-Z. Anything else (and lowercase, folded to
 * uppercase by the caller) not in that set renders blank — enough
 * for kernel banners/debug text; more glyphs can be added later.
 *
 * Each glyph is 8 bytes, one per row, MSB = leftmost pixel.
 */

